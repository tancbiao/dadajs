LS.Tropes = {
  all(){ return LS.SYS_TROPES; },
  byId(id){ return LS.SYS_TROPES.find(function(t){ return t.id === id; }) || null; },
  /* 按标签挑 n 个，尽量不重复分组 */
  pick(tags, rnd, n){
    const t = tags || [];
    const scored = LS.SYS_TROPES.map(function(x){
      let s = 0;
      (x.tags || []).forEach(function(g){ if (t.indexOf(g) >= 0) s += 5; });
      (x.group ? [x.group] : []).forEach(function(g){ if (t.indexOf(g) >= 0) s += 3; });
      return { x:x, s:s + rnd() * 2 };
    }).sort(function(a,b){ return b.s - a.s; });
    const out = [];
    const usedGroup = {};
    for (let i = 0; i < scored.length && out.length < (n || 3); i++) {
      const it = scored[i];
      if (it.s < 4) continue;
      if (usedGroup[it.x.group] && out.length >= 2) continue;
      usedGroup[it.x.group] = 1;
      out.push(it.x);
    }
    for (let i = 0; i < scored.length && out.length < (n || 3); i++) {
      if (out.indexOf(scored[i].x) < 0) out.push(scored[i].x);
    }
    return out;
  },
  routeOf(trope, rnd){
    if (!trope || !trope.routes || !trope.routes.length) return null;
    return trope.routes[Math.floor(rnd() * trope.routes.length)];
  },
  /* 转成知识库支线条目，供 AI 与离线事件使用 */
  toSeed(trope, route){
    return { t: trope.n + '·' + route.n, s: (trope.core || '') + ' ' + route.d };
  }
};
