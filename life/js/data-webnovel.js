LS.Webnovel = {
  /* 按世界标签挑 2-3 条支线，优先契合度高、不重复的 */
  seeds(tags, rnd, n){
    const t = tags || [];
    const score = LS.WEBNOVEL_ARCH.map(function(a){
      let s = 0;
      (a.tags || []).forEach(function(x){ if (t.indexOf(x) >= 0) s += 5; });
      return { a:a, s:s + rnd() * 1.5 };
    }).sort(function(x,y){ return y.s - x.s; });
    const out = [];
    const want = n || 3;
    for (let i = 0; i < score.length && out.length < want; i++) {
      // 每个套路只出一条，避免同一套路重复
      if (score[i].s < 4) continue;
      const a = score[i].a;
      const pick = a.seeds[Math.floor(rnd() * a.seeds.length)];
      out.push({ t: a.name + '·' + pick.t, s: pick.s });
    }
    // 契合的套路不够，才用通用条目补
    if (out.length < want) {
      const generic = ['守护/团宠', '废柴逆袭', '系统流'];
      LS.WEBNOVEL_ARCH.forEach(function(a){
        if (out.length >= want) return;
        if (generic.indexOf(a.name) < 0) return;
        if (out.some(function(x){ return x.t.indexOf(a.name) === 0; })) return;
        const pick = a.seeds[Math.floor(rnd() * a.seeds.length)];
        out.push({ t: a.name + '·' + pick.t, s: pick.s });
      });
    }
    return out.slice(0, want);
  }
};
