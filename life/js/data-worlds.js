LS.worldById = function(id){
  return LS.WORLDS.find(function(w){ return w.id === id; }) || LS.WORLDS[0];
};
LS.pick = function(arr, rnd){
  if (!arr || !arr.length) return '';
  const r = rnd ? rnd() : Math.random();
  return arr[Math.floor(r * arr.length) % arr.length];
};
